import {test} from 'node:test';
import {expect} from 'playwright/test';
import {productionReader} from './http-reader';
import {artifactPath} from './artifacts';

const databaseUrlFile=process.env.OKO_TEST_DATABASE_URL_FILE;

test('PostgreSQL reader authenticates, collects through UI, renders media and summaries, and survives restart', {timeout:60000,skip:!databaseUrlFile}, async t=>{
  const {page,api,origin,restart,setProcessingState}=await productionReader(t,{persistent:true,databaseUrlFile});
  const errors:string[]=[];
  page.on('pageerror',error=>errors.push(error.stack??error.message));
  await api('settings/oko/global','PATCH',{theses:false,prompt_filters:''});
  await api('power','PUT',{enabled:true});
  await page.goto(origin+'/');
  await expect(page.getByLabel('Логин')).toBeVisible();
  await expect(page.locator('#reader-shell')).toHaveCount(0);
  await page.screenshot({path:artifactPath('postgres-native-login.png'),fullPage:true});
  await page.getByLabel('Логин').fill('reader');
  await page.getByLabel('Пароль').fill('synthetic-password');
  await page.getByRole('button',{name:'Войти'}).click();
  await expect(page.locator('#add-open')).toBeEnabled();
  await page.locator('#add-open').click();
  await page.locator('#rss-url').fill('https://a.test/feed');
  await page.locator('#rss-check').click();
  await expect(page.locator('#rss-add')).toBeEnabled();
  await page.locator('#rss-folder-new').fill('PostgreSQL library');
  await page.locator('#rss-add').click();
  await expect(page.locator('#feeds-dialog')).toBeVisible();
  await page.locator('#feeds-close').click();
  await expect(page.locator('#cards button')).toHaveCount(1,{timeout:15000});
  await expect(page.locator('#cards img')).toHaveCount(1);
  await expect.poll(()=>page.locator('#cards img').evaluateAll(images=>images.every(image=>(image as HTMLImageElement).naturalWidth>0))).toBe(true);
  await page.locator('#cards button').click();
  await expect(page.locator('#title')).toContainText('Статья');
  const refreshed=page.waitForResponse(response=>new URL(response.url()).pathname==='/api/v3/collect'&&response.request().method()==='POST');
  await page.getByRole('button',{name:'Refresh Sources',exact:true}).click();
  expect((await refreshed).status()).toBe(200);
  await expect(page.locator('#title')).toContainText('Статья');
  await expect.poll(()=>page.locator('#images img').evaluateAll(images=>images.some(image=>image instanceof HTMLImageElement&&image.naturalWidth>0))).toBe(true);
  await page.screenshot({path:artifactPath('postgres-native-refreshed.png'),fullPage:true});
  await setProcessingState('ready');
  await api('processors/llamacpp','PUT',{endpoint:'http://localhost:9931',model:'local:latest',local_execution:true});
  await api('settings/oko/global','PATCH',{processor:'llamacpp',theses:true,prompt_filters:'Keep useful text'});
  await expect(page.locator('#theses')).toContainText('Просмотрено удаляет текст.',{timeout:15000});
  await page.screenshot({path:artifactPath('postgres-native-reader.png'),fullPage:true});
  await restart();
  await expect(page.getByRole('button',{name:'Reload Oko'})).toBeVisible({timeout:10000});
  await page.getByRole('button',{name:'Reload Oko'}).click();
  await expect(page.getByRole('button',{name:'Выйти'})).toBeVisible();
  await expect(page.locator('#cards button')).toHaveCount(1);
  await page.locator('#cards button').click();
  await expect(page.locator('#theses')).toContainText('Просмотрено удаляет текст.');
  await page.locator('#viewed').click();
  await expect(page.locator('#cards button')).toHaveCount(0);
  await page.getByRole('button',{name:'Выйти'}).click();
  await expect(page.getByLabel('Логин')).toBeVisible();
  expect(errors).toEqual([]);
});
