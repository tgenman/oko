import {test} from 'node:test';
import assert from 'node:assert/strict';
import {expect} from 'playwright/test';
import {productionReader} from './http-reader';
import {artifactPath} from './artifacts';

test('migrated publication shows latest text and media without stored history', {timeout:30000}, async t=>{
  const r=await productionReader(t,{publicationPipeline:true});
  await r.api('settings/oko/global','PATCH',{theses:false,prompt_filters:'',telegram_http_rps:10});
  await r.openReader();
  await r.api('telegram/connect','POST',{source_locator:'@lateststate',folder:'Inbox',initial_history:{mode:'count',count:'1'}});
  await expect(r.page.locator('[data-card]')).toHaveCount(1);
  await expect.poll(async()=>{const cards=await r.api('cards');return cards[0]?.availability==='available'&&!cards[0].loading;}).toBe(true);
  await r.page.locator('[data-card]').click();
  await expect(r.page.locator('#text')).toContainText('Initial publication');
  await expect(r.page.locator('#images img')).toHaveAttribute('src',/^blob:/);
  const cards=await r.api('cards'), id=cards[0].id;
  await r.updatePublication('Updated publication');
  await r.api(`materials/${id}/retry`,'POST');
  await expect.poll(async()=>{const material=await r.api(`materials/${id}`);return material.availability==='available'&&material.content.text==='Updated publication'&&!material.content.loading;}).toBe(true);
  await r.page.reload();
  await expect(r.page.locator('[data-card]')).toHaveCount(1);
  await r.page.locator('[data-card]').click();
  await expect(r.page.locator('#text')).toContainText('Updated publication');
  await expect(r.page.locator('#images img')).toHaveAttribute('src',/^blob:/);
  await expect(r.page.locator('#versions')).toBeHidden();
  const current=await r.api(`materials/${id}`);
  assert.equal(current.availability,'available');
  if(current.availability==='available') assert.deepEqual(current.content.previous_versions,[]);
  await r.page.screenshot({path:artifactPath('latest-publication-desktop.png')});
  await r.page.setViewportSize({width:390,height:844});
  await r.page.locator('#text').scrollIntoViewIfNeeded();
  await r.page.screenshot({path:artifactPath('latest-publication-mobile.png')});
  await r.page.locator('#viewed').click();
  await expect(r.page.locator('[data-card]')).toHaveCount(0);
  await expect(r.page.locator('#text')).toContainText('Updated publication');
  await r.page.reload();
  await expect(r.page.locator('#material')).toBeHidden();
});
