import {test} from 'node:test';
import {expect} from 'playwright/test';
import {productionReader} from './http-reader';
import {addSources} from './connections';
import {artifactPath} from './artifacts';
import {openAdmin} from './admin-navigation';

test('conflicting feed ownership is visible without moving or duplicating the publication',{timeout:45000},async t=>{
 const r=await productionReader(t,{publicationPipeline:true});
 await r.setYoutubeState('ready');
 await r.api('settings/oko/global','PATCH',{theses:false,prompt_filters:''});
 await r.openReader();
 await addSources(r.api,[['https://www.youtube.com/feeds/videos.xml?channel_id=UCaaaaaaaaaaaaaaaaaaaaaa','First','One'],['https://www.youtube.com/feeds/videos.xml?channel_id=UCbbbbbbbbbbbbbbbbbbbbbb','Second','Two']]);
 await expect(r.page.locator('[data-card]')).toHaveCount(1);
 const cards=(await r.api('cards')).items;
 const item=cards[0]!.id;
 const original=await r.api(`publication/${item}`);
 await expect.poll(async()=>JSON.stringify(await r.api('status/details')),{timeout:15000}).toContain('Publication ownership conflict');
 const status=JSON.stringify(await r.api('status/details'));
 expect(status).toContain(item);
 expect(status).toContain(original.feed_id);
 expect((await r.api('cards')).items.map(card=>card.id)).toEqual([item]);
 const feeds=(await r.api('reading-composition')).feeds;
 expect(feeds.map(feed=>feed.count).sort()).toEqual([0,1]);
 await openAdmin(r.page);
 await r.page.locator('#status-toggle').click();
 const problem=r.page.locator('.status-problem').filter({hasText:'Publication ownership conflict'});
 await problem.locator('summary').click();
 await expect(problem.getByText(/Publication ownership conflict/)).toBeVisible();
 await r.page.screenshot({path:artifactPath('publication-ownership-conflict.png')});
});
