import {test} from 'node:test';
import {expect} from 'playwright/test';
import {productionReader} from './http-reader';
import {artifactPath} from './artifacts';

test('external Telegram media show typed badges and cards without false download errors',{timeout:25000},async t=>{
 const {page,api,openReader}=await productionReader(t);
 await api('v3/settings/oko/global','PATCH',{theses:false,prompt_filters:'',telegram_http_rps:10});
 await openReader();
 await api('v3/telegram/connect','POST',{source_locator:'@externalmedia',folder:'News'});
 const video=page.locator('[data-card]').filter({hasText:'External video post'});
 const external=page.locator('#text [aria-label="External media"]');
 await expect(video.locator('[aria-label="Видео доступно у источника"]')).toBeVisible();
 await video.click();
 await expect(external).toContainText('File exceeds the available size limit.');
 await expect(external).toContainText('0:58');
 await expect(external.locator('img')).toBeVisible();
 await expect(page.locator('#text video')).toHaveCount(0);
 await expect(external.locator('a')).toHaveAttribute('href','https://t.me/externalmedia/12');
 await expect(page.locator('#retry')).toBeHidden();
 await expect(page.locator('#status-toggle')).toHaveText('Problems · 0');
 await page.screenshot({path:artifactPath('external-video-desktop.png')});
 await page.setViewportSize({width:390,height:844});
 await external.screenshot({path:artifactPath('external-video-mobile.png')});
 await page.setViewportSize({width:1280,height:900});
 const audio=page.locator('[data-card]').filter({hasText:'External audio post'});
 await expect(audio.locator('[aria-label="Аудио доступно у источника"]')).toBeVisible();
 await audio.click();
 await expect(external).toContainText('A recorded lesson');
 await expect(external).toContainText('Fixture author');
 await expect(external.locator('a')).toHaveText('Open original ↗');
 await expect(external).not.toContainText('size limit');
 await expect(page.locator('#retry')).toBeHidden();
 await expect.poll(async()=>{const status=await api('v3/status/details');return status.problems.count;}).toBe(0);
 await page.screenshot({path:artifactPath('external-audio-desktop.png')});
 const document=page.locator('[data-card]').filter({hasText:'External document post'});
 await expect(document.getByRole('img',{name:'Файл доступен у источника',exact:true})).toBeVisible();
 await document.click();
 await expect(external).toContainText('Бесы.txt');
 await expect(external).toContainText('36.2 KB');
 await expect(external.locator('a')).toHaveAttribute('href','https://t.me/externalmedia/13');
 await expect(page.locator('#retry')).toBeHidden();
 await document.locator('.external-media-badges').hover();
 await page.screenshot({path:artifactPath('external-document-desktop.png')});
 await audio.click();
 await expect(external).not.toContainText('Бесы.txt');
 await document.click();
 await expect(external).toContainText('Бесы.txt');
});
