import {addSources} from './connections';
import {test} from 'node:test';
import {expect} from 'playwright/test';
import {productionReader} from './http-reader.ts';
import assert from 'node:assert/strict';

test('production HTTP reader keeps folder/feed membership, previews, theses and viewed actions', {timeout:45000}, async t => {
 const {page, api, origin, token} = await productionReader(t);
  assert.equal((await fetch(origin+'/api/v3/cards')).status,403);
  await api('settings/oko/global','PATCH',{theses:false,processor:'llamacpp'});
  const plan=await addSources(api, [["https://a.test/feed", "Альфа", "Наука"], ["https://b.test/feed", "Бета", "Наука"], ["https://empty.test/feed", "Пустой", "Наука"]]);
  const errors: string[]=[]; page.on('pageerror',error=>errors.push(error.message));
  await page.goto(origin+'/#token='+token);
  await expect.poll(async()=>{const cards=(await api('cards')).items; return cards.length===2&&cards.every(c=>!c.loading);},{timeout:15000}).toBe(true);
  await expect(page.locator('#cards button')).toHaveCount(2);
  await expect(page.locator('#cards .card-snippet')).toHaveCount(0);
  await expect(page.locator('#cards img')).toHaveCount(2);
  await expect.poll(()=>page.locator('#cards img').evaluateAll(images=>images.every(img=>(img as HTMLImageElement).complete&&(img as HTMLImageElement).naturalWidth>0))).toBe(true);
  const alpha=plan.feeds.find(feed=>feed.title==='Альфа'), beta=plan.feeds.find(feed=>feed.title==='Бета'), empty=plan.feeds.find(feed=>feed.title==='Пустой');
  const navigation=await api('reading-composition'), folder=navigation.folders.find(folder=>folder.title==='Наука');
  await page.locator(`[data-folder="${folder!.id}"]`).click();
  await expect(page.locator('#count-label')).toHaveText('2');
  for(const feed of [alpha,beta]){
   await page.locator(`[data-feed="${feed!.id}"]`).click();
   await expect(page.locator('#cards button')).toHaveCount(1);
   await expect(page.locator('#cards .card-source')).toHaveCount(0);
   await expect(page.locator('#cards button')).toHaveAttribute('aria-label',new RegExp(feed!.title));
  }
  await api('processors/llamacpp','PUT',{endpoint:'http://localhost:9931',model:'local:latest',local_execution:true});
  await api('settings/oko/global','PATCH',{theses:true});
  await expect.poll(async()=>{const cards=(await api('cards')).items;return cards.length===2&&(await Promise.all(cards.map(c=>api(`materials/${c.id}`)))).every(c=>!!c.theses.result);},{timeout:15000}).toBe(true);
  await expect(page.locator(`[data-feed="${empty!.id}"]`)).toHaveCount(0);
  await page.locator('#read-feeds-toggle').click();
  await page.locator(`[data-feed="${empty!.id}"]`).click();
  await expect(page.locator('#cards button')).toHaveCount(0);
  await expect(page.locator('#list-status')).toHaveText('No items');
  await page.locator(`[data-folder="${folder!.id}"]`).click();
  await expect(page.locator('#count-label')).toHaveText('2');
  await expect(page.locator(`[data-folder="${folder!.id}"] .tree-count`)).toHaveText('2');
  await page.locator('#cards button').first().click();
  await expect(page.locator('#title')).toContainText('Статья');
  await expect(page.locator('#theses')).toContainText('Просмотрено удаляет текст.');
  await page.locator('#viewed').click();
  await expect(page.locator('#cards button')).toHaveCount(1);
  await page.locator('#cards button').click();
  await expect(page.locator('#title')).toContainText('Статья');
  await page.locator('#viewed').click();
  await expect(page.locator('#cards button')).toHaveCount(0);
  assert.deepEqual((await api('cards')).items,[]); assert.equal((await api('reading-composition')).count,0);
  assert.deepEqual(errors,[]);
});
