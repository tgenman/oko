import {test} from 'node:test';
import {expect} from 'playwright/test';
import {productionReader} from './http-reader';
import {feedOptions} from './settings-actions';
import {artifactPath} from './artifacts';

test('explicit channel access changes keep the feed and publication in the real reader',{timeout:30000},async t=>{
 const r=await productionReader(t,{publicationPipeline:true});
 await r.api('settings/oko/global','PATCH',{theses:false,prompt_filters:'',telegram_http_rps:10});
 await r.openReader();
 await r.api('telegram/profiles/personal','PUT',{configuration_ref:'one'});
 const connection=await r.api('telegram/connect','POST',{source_locator:'@switchfixture',folder:'Inbox',initial_history:{mode:'count',count:'1'}});
 if(!connection||typeof connection!=='object'||!('feed_id'in connection)||typeof connection.feed_id!=='string')throw new Error('Missing connected feed');
 const feed=connection.feed_id;
 await expect(r.page.locator('[data-card]')).toHaveCount(1);
 const item=(await r.api('cards'))[0]!.id;
 await r.page.locator('[data-card]').click();
 await expect(r.page.locator('#text')).toContainText('Web original');
 const open=async()=>{await r.page.locator('#feeds-open').click();await r.page.locator(`[data-owner="feed/${feed}"]`).click();await feedOptions(r.page);};
 await open();
 await r.page.locator('#feed-telegram-access').selectOption('personal');
 await r.page.locator('#feed-telegram-change').click();
 await expect(r.page.locator('#feed-telegram-status')).toContainText('Access changed');
 await expect(r.page.locator('#feed-options').getByText(/^Personal Account ·/)).toBeVisible();
 await r.page.screenshot({path:artifactPath('telegram-client-access-changed.png')});
 await r.page.locator('#feeds-close').click();
 await r.page.getByRole('button',{name:'Show new version',exact:true}).click();
 await expect(r.page.locator('#text')).toContainText('Client original');
 await expect(r.page.locator('#images img')).toHaveAttribute('src',/^blob:/);
 expect((await r.api('cards')).map(c=>c.id)).toEqual([item]);
 await r.page.screenshot({path:artifactPath('telegram-client-publication.png')});
 await open();
 await r.page.locator('#feed-telegram-access').selectOption('web');
 await r.page.locator('#feed-telegram-change').click();
 await expect(r.page.locator('#feed-telegram-status')).toContainText('Access changed');
 await r.page.locator('#feeds-close').click();
 await r.page.getByRole('button',{name:'Show new version',exact:true}).click();
 await expect(r.page.locator('#text')).toContainText('Web original');
 expect((await r.api('cards')).map(c=>c.id)).toEqual([item]);
 await r.page.screenshot({path:artifactPath('telegram-web-access-restored.png')});
});
