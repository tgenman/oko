"""Speed optimizations retain the real CLI failure boundaries."""
import json
import os
from pathlib import Path
import subprocess
import sys

from tests.support.build_tools import api_repository

ROOT = Path(__file__).resolve().parents[2]


def run(root, *args):
    return subprocess.run(args, cwd=root, env={**os.environ, 'OKO_PYTHON': sys.executable},
                          capture_output=True, text=True)


def test_api_cache_reuses_only_success_for_exact_inputs_and_outputs(tmp_path):
    api_repository(tmp_path)
    command = ('node', '--import', 'tsx', 'scripts/generate-api.mts')
    generated = run(tmp_path, *command, 'generate')
    assert generated.returncode == 0, generated.stdout + generated.stderr
    checked = run(tmp_path, *command, 'check')
    assert checked.returncode == 0, checked.stdout + checked.stderr
    hit = run(tmp_path, *command, 'check')
    assert hit.returncode == 0 and 'API check cache hit' in hit.stdout
    fresh = run(tmp_path, *command, 'check', '--fresh')
    assert fresh.returncode == 0 and 'API check cache hit' not in fresh.stdout
    lock = tmp_path / 'uv.lock'
    locked = lock.read_bytes()
    lock.write_bytes(locked + b'\n# lock input changed\n')
    rechecked = run(tmp_path, *command, 'check')
    assert rechecked.returncode == 0, rechecked.stdout + rechecked.stderr
    assert 'API check cache hit' not in rechecked.stdout
    lock.write_bytes(locked)
    path = tmp_path / 'frontend/src/api/generated/revision.ts'
    saved = path.read_bytes()
    path.write_bytes(saved + b'// unexpected generated bytes\n')
    failed = run(tmp_path, *command, 'check')
    assert failed.returncode != 0 and 'Stale TypeScript API library' in failed.stderr
    path.write_bytes(saved)
    assert 'API check cache hit' in run(tmp_path, *command, 'check').stdout


def test_published_assets_reject_damage_inventory_and_wrong_build_receipt(tmp_path):
    code = "import {validateAssets} from " + json.dumps(str(ROOT / 'scripts/frontend-assets.mts')) + ";" + r"""
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {promises as fs} from 'node:fs';
import path from 'node:path';
const hash = value => createHash('sha256').update(value).digest('hex');
const root = process.argv[1], assets = {'index.html': hash('page'), 'transport.js': hash('transport')};
const generation = hash(JSON.stringify(assets)), directory = path.join(root, 'generations', generation);
await fs.mkdir(directory, {recursive: true});
await fs.writeFile(path.join(directory, 'index.html'), 'page');
await fs.writeFile(path.join(directory, 'transport.js'), 'transport');
const manifest = {source: 'source', contract: 'contract', check: 'production', generation, assets};
const save = value => fs.writeFile(path.join(root, 'current.json'), JSON.stringify(value));
await save(manifest);
await validateAssets(root, 'source', 'contract', 'production');
await assert.rejects(validateAssets(root, 'source', 'contract', 'development'), /inputs changed/);
await assert.rejects(validateAssets(root, 'different', 'contract'), /stale/);
await assert.rejects(validateAssets(root, 'source', 'different'), /Mixed/);
await fs.writeFile(path.join(directory, 'index.html'), 'corrupt');
await assert.rejects(validateAssets(root, 'source', 'contract'), /corrupt/);
await fs.writeFile(path.join(directory, 'index.html'), 'page');
await save({...manifest, assets: {'index.html': assets['index.html']}});
await assert.rejects(validateAssets(root, 'source', 'contract'), /inventory/);
await save(manifest);
await fs.unlink(path.join(directory, 'transport.js'));
await assert.rejects(validateAssets(root, 'source', 'contract'), /ENOENT/);
"""
    result = run(ROOT, 'node', '--import', 'tsx', '--input-type=module', '-e', code, str(tmp_path))
    assert result.returncode == 0, result.stdout + result.stderr


def test_browser_batches_reuse_workers_and_preserve_failures_filters_and_hooks(tmp_path):
    files=[]
    for index in range(4):
        file=tmp_path/f'test_batch_{index}.ts'
        file.write_text("const {test,after}=require('node:test');\n"
            +f"test('batch case {index}',()=>{{console.log('EXEC {index} '+process.pid);if({index}===1)throw Error('deliberate failure');}});\n"
            +f"after(()=>console.log('CLEAN {index}'));\n")
        files.append(str(file))
    # Tools CI has no Chromium. Exercise the same batching owner directly;
    # suite-browser process/interrupt cleanup is tested in the browser group.
    harness="""
const {batchTests}=require(process.argv[1]);
const {spawnSync}=require('node:child_process');
(async()=>{
  const batch=await batchTests(process.argv.slice(2));
  try {process.exitCode=spawnSync(process.execPath,batch.args,{stdio:'inherit'}).status??1;}
  finally {await batch.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
"""
    command=('node','--require','tsx/cjs','-e',harness,'--',str(ROOT/'scripts/browser-batches.cts'),
        '--require','tsx/cjs','--require',str(ROOT/'scripts/register-browser-typescript.cts'),
        '--test','--test-reporter=tap','--test-concurrency=2')
    result=run(ROOT,*command,*files)
    assert result.returncode==1,result.stdout+result.stderr
    import re
    executed=re.findall(r'EXEC (\d) (\d+)',result.stdout)
    assert {index for index,_ in executed}==set('0123'),result.stdout+result.stderr
    assert len({pid for _,pid in executed})==2,result.stdout
    assert set(re.findall(r'CLEAN (\d)',result.stdout))==set('0123'),result.stdout
    assert 'deliberate failure' in result.stdout
    filtered=run(ROOT,*command,'--test-name-pattern=batch case 3',*files)
    assert filtered.returncode==0,filtered.stdout+filtered.stderr
    assert [index for index,_ in re.findall(r'EXEC (\d) (\d+)',filtered.stdout)]==['3'],filtered.stdout

    Path(files[0]).write_text("throw Error('load explosion');")
    broken=run(ROOT,*command,'--test-name-pattern=batch case 3',*files)
    assert broken.returncode!=0,broken.stdout+broken.stderr
    assert 'EXEC 3 ' in broken.stdout,broken.stdout
