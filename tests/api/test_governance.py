@pytest.mark.parametrize('fault,location', [
    ('missing_schema', 'schema GovernanceProbe'),
    ('invalid_schema', 'schema GovernanceProbe'),
    ('invalid_format', 'schema GovernanceProbe'),
    ('missing_response', 'GET /api/probe response 200 application/json'),
    ('invalid_response', 'GET /api/probe response 200 application/json'),
    ('invalid_named_response', 'GET /api/probe response 200 application/json'),
])
def test_validate_and_bundle_reject_bad_examples_before_output(tmp_path, fault, location):
    value, spec, _ = documents(tmp_path)
    schema = value['components']['schemas']['GovernanceProbe']
    response = value['paths']['/api/probe']['get']['responses']['200']['content']['application/json']
    if fault == 'missing_schema':
        del schema['examples']
    elif fault == 'invalid_schema':
        schema['examples'] = [{'value': 42}]
    elif fault == 'invalid_format':
        schema['properties']['value']['format'] = 'date-time'
    elif fault == 'missing_response':
        del response['example']
    elif fault == 'invalid_response':
        response['example'] = {'value': 42}
    else:
        del response['example']
        response['examples'] = {'valid': {'value': {'value': 'fixture'}}, 'invalid': {'value': {}}}
    spec.write_text(json.dumps(value))
    for command in ['validate', 'bundle']:
        output = tmp_path / 'must-not-be-written.json'
        output.write_text('preserve existing output')
        result = run(sys.executable, str(ROOT / 'scripts/api.py'), command, '--spec', str(spec), '--output', str(output))
        assert result.returncode != 0
        assert location in result.stderr, result.stderr
        assert output.read_text() == 'preserve existing output'
        assert not result.stdout


def test_false_null_and_named_response_examples_and_binary_exception(tmp_path):
    value, spec, _ = documents(tmp_path)
    value['components']['schemas']['Nullable'] = {'type': ['boolean', 'null'], 'examples': [None, False]}
    responses = value['paths']['/api/probe']['get']['responses']
    responses['200']['content']['application/json'] = {
        'schema': {'$ref': '#/components/schemas/Nullable'},
        'example': None,
    }
    responses['201'] = {'description': 'named samples', 'content': {'application/json': {
        'schema': {'$ref': '#/components/schemas/Nullable'},
        'examples': {'null': {'value': None}, 'false': {'value': False}},
    }}}
    responses['202'] = {'description': 'binary', 'content': {'application/octet-stream': {
        'schema': {'type': 'string', 'format': 'binary'},
    }}}
    spec.write_text(json.dumps(value))
    result = run(sys.executable, str(ROOT / 'scripts/api.py'), 'bundle', '--spec', str(spec))
    assert result.returncode == 0, result.stderr
    assert json.loads(result.stdout) == value


@pytest.mark.parametrize('command', ['generate', 'check'])
def test_sdk_commands_reject_missing_examples_without_rewriting_libraries(tmp_path, command):
    from tests.support.build_tools import api_repository
    api_repository(tmp_path)
    for directory in ['frontend/src/api/generated', 'oko/reader/generated']:
        target = tmp_path / directory
        target.mkdir(parents=True)
        (target / 'sentinel.txt').write_text('preserve generated bytes')
    spec = tmp_path / 'api/openapi.yaml'
    value = json.loads(spec.read_text())
    del value['components']['schemas']['Probe']['examples']
    spec.write_text(json.dumps(value))
    result = run('node', '--import', 'tsx', 'scripts/generate-api.mts', command, cwd=tmp_path)
    assert result.returncode != 0
    assert 'Missing examples: schema Probe' in result.stdout + result.stderr
    for directory in ['frontend/src/api/generated', 'oko/reader/generated']:
        target = tmp_path / directory
        assert [file.name for file in target.iterdir()] == ['sentinel.txt']
        assert (target / 'sentinel.txt').read_text() == 'preserve generated bytes'
