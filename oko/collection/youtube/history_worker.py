"""Public playlist metadata only; a fresh process isolates yt-dlp and its state."""
import json
import re
import sys
import time
from typing import Any
from urllib.parse import urlsplit
from oko.diagnostics import exception_details


class PortionEnd(Exception):
    pass


def collect(channel: str, count: int, state: dict[str, Any]) -> dict[str, Any]:
    from yt_dlp import YoutubeDL  # type: ignore[import-untyped]

    if not re.fullmatch(r'UC[A-Za-z0-9_-]{22}', channel) or count < 1:
        raise ValueError('Неверный канал или количество')
    state.setdefault('lists', {})
    state.setdefault('done', [])
    state.setdefault('anchors', {})
    state.setdefault('replay', {})
    calls = 0
    portion_ended = False
    network_error: Exception | None = None
    # A recovered prefix has its own finite allowance, so recovery does not
    # forever consume the budget intended for eight NEW page requests.
    budget = 8 + sum(state['replay'].values())
    deadline = time.monotonic() + 120

    class Listing(YoutubeDL):  # type: ignore[misc]
        def urlopen(self, request: Any) -> Any:
            nonlocal calls, portion_ended, network_error
            url = urlsplit(request if isinstance(request, str) else request.url)
            if url.hostname != 'www.youtube.com' or url.path not in ('/playlist', '/youtubei/v1/browse'):
                raise ValueError('Запрос вне списка YouTube запрещён')
            if calls >= budget or time.monotonic() >= deadline:
                portion_ended = True
                raise PortionEnd()
            calls += 1
            try:
                return super().urlopen(request)
            except Exception as exc:
                network_error = exc
                raise

    options = dict(extract_flat=True, simulate=True, skip_download=True, quiet=True,
                   no_warnings=True, cachedir=False, retries=0, extractor_retries=0,
                   socket_timeout=10, proxy='', compat_opts={'no-youtube-unavailable-videos'})
    error = None
    diagnostic = None
    complete = False
    kind = ''
    start_calls = 0
    try:
        with Listing(options) as ydl:
            for kind in ('UULF', 'UULV', 'UU'):
                if kind in state['done']:
                    continue
                start_calls = calls
                values = state['lists'].setdefault(kind, [])
                seen = {entry['id'] for entry in values}
                allowed = {entry['id'] for group in ('UULF', 'UULV') for entry in state['lists'].get(group, [])}
                anchor = state['anchors'].get(kind)
                anchored = not anchor
                try:
                    info = ydl.extract_info(f'https://www.youtube.com/playlist?list={kind}{channel[2:]}', download=False, process=False)
                except Exception as exc:
                    # YouTube does not create an autogenerated category playlist
                    # when the channel has never published that type. The overall
                    # Uploads playlist must still succeed before declaring EOF.
                    if kind != 'UU' and 'YouTube said: The playlist does not exist.' in str(exc):
                        state['done'].append(kind)
                        state['replay'].pop(kind, None)
                        continue
                    raise
                if not info or info.get('_type') != 'playlist':
                    raise ValueError('YouTube не вернул список публикаций')
                for entry in info['entries']:
                    identity = entry.get('id', '')
                    if not re.fullmatch(r'[A-Za-z0-9_-]{11}', identity):
                        continue
                    if not state['anchors'].get(kind):
                        state['anchors'][kind] = identity
                    if identity == anchor:
                        anchored = True
                    if not anchored:
                        continue  # New uploads do not move a resumed boundary.
                    if entry.get('live_status') in ('is_live', 'is_upcoming', 'post_live'):
                        continue
                    if kind == 'UU' and identity not in allowed:
                        continue
                    if identity not in seen:
                        values.append(dict(id=identity, title=entry.get('title') or 'YouTube'))
                        seen.add(identity)
                    if len(values) >= count:
                        break
                if network_error:
                    raise network_error
                if portion_ended:
                    raise PortionEnd()
                if not anchored:
                    raise ValueError('Граница истории исчезла; остановите операцию и начните новый подбор')
                state['done'].append(kind)
                state['replay'].pop(kind, None)
            complete = True
    except PortionEnd:
        pass
    except Exception as exc:
        if not portion_ended:
            error = str(exc)[:1000] or type(exc).__name__
            diagnostic = exception_details(exc)
    if not complete and kind:
        state['replay'][kind] = max(state['replay'].get(kind, 0), calls - start_calls)
    return dict(entries=state['lists'].get('UU', [])[:count], state=state,
                complete=complete, error=error, requests=calls, diagnostic=diagnostic)


def main() -> None:
    try:
        request = json.load(sys.stdin)
        result = collect(request['channel'], request['count'], request.get('state', {}))
    except Exception as exc:
        result = dict(entries=[], complete=False, state={}, error=str(exc)[:1000], requests=0)
    sys.stdout.write(json.dumps(result, ensure_ascii=False))


if __name__ == '__main__':
    main()
