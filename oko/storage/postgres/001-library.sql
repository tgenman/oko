CREATE TABLE feed_details (
            feed TEXT PRIMARY KEY, created double precision, modified double precision, updated double precision,
            marked_read double precision, description TEXT);

CREATE TABLE feeds (
          id TEXT PRIMARY KEY, identity TEXT UNIQUE, title TEXT, kind TEXT, folder_id TEXT,
          original_urls TEXT, connection TEXT, transport TEXT,
          importance TEXT DEFAULT 'normal', initial_days bigint DEFAULT 1,
          public_ai bigint DEFAULT 0, read_history bigint DEFAULT 0, auto_read bigint,
          telegram_peer bigint,telegram_account TEXT,telegram_username TEXT, platform TEXT, external_id TEXT, url TEXT NOT NULL DEFAULT '', description TEXT NOT NULL DEFAULT '', created_at double precision, enabled bigint NOT NULL DEFAULT 1, adapter TEXT NOT NULL DEFAULT '', config TEXT NOT NULL DEFAULT '{}', cursor TEXT NOT NULL DEFAULT '', interval_seconds bigint NOT NULL DEFAULT 1200, filter_config TEXT NOT NULL DEFAULT '{}', summary_config TEXT NOT NULL DEFAULT '{}');

CREATE TABLE filter_inputs (item TEXT PRIMARY KEY,signature TEXT);

CREATE TABLE folders (id TEXT PRIMARY KEY, title TEXT UNIQUE, position bigint);

CREATE TABLE history_members (feed TEXT, item TEXT, outcome TEXT DEFAULT 'pending', PRIMARY KEY(feed,item));

CREATE TABLE initial_history (feed TEXT PRIMARY KEY, selection TEXT, frozen bigint DEFAULT 0, paused bigint DEFAULT 0,scan_complete bigint DEFAULT 1);

CREATE TABLE items (
          id TEXT PRIMARY KEY,source_id TEXT UNIQUE,url TEXT,published double precision,
          viewed bigint DEFAULT 0,complete bigint DEFAULT 0,feed_id TEXT,
          members TEXT DEFAULT '[]',published_known bigint DEFAULT 1,source_order bigint,platform TEXT,external_id TEXT,title TEXT NOT NULL DEFAULT '',published_at double precision,discovered_at double precision,content TEXT NOT NULL DEFAULT '{}',media_ids TEXT NOT NULL DEFAULT '[]',filtered_content TEXT NOT NULL DEFAULT '{}',summarized_content TEXT NOT NULL DEFAULT '{}',processing_metadata TEXT NOT NULL DEFAULT '{}',status TEXT NOT NULL DEFAULT 'pending_collection');

CREATE TABLE jobs (
          id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,kind TEXT,item TEXT DEFAULT '',status TEXT DEFAULT 'pending',
          attempt bigint DEFAULT 0,next double precision DEFAULT 0,generation bigint DEFAULT 0,error TEXT,
          manual_once bigint DEFAULT 0,problem_code TEXT,retry_at double precision,retry_delay double precision NOT NULL DEFAULT 0,wait_scope TEXT, payload TEXT NOT NULL DEFAULT '{}', queued_wall double precision,
          UNIQUE(kind,item));

CREATE TABLE processing_dirty (item TEXT PRIMARY KEY);

CREATE TABLE processing_stage_dirty (kind TEXT,item TEXT,PRIMARY KEY(kind,item));

CREATE TABLE reader_action_results (
              sequence bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, id TEXT UNIQUE NOT NULL, identity TEXT NOT NULL,
              body TEXT NOT NULL, started double precision NOT NULL, completed double precision, result TEXT NOT NULL);

CREATE TABLE reader_action_superseded (sequence bigint PRIMARY KEY, completed double precision);

CREATE TABLE reader_entities (
          kind TEXT, identity TEXT, version bigint NOT NULL, changed double precision NOT NULL,
          PRIMARY KEY(kind,identity));

CREATE TABLE reader_feed_counts (feed TEXT PRIMARY KEY, unviewed bigint NOT NULL, visible bigint NOT NULL);

CREATE TABLE reader_folder_counts (folder TEXT PRIMARY KEY, visible bigint NOT NULL);

CREATE TABLE reader_identity (id bigint PRIMARY KEY CHECK(id=1), value TEXT NOT NULL);

CREATE TABLE reader_job_time (job bigint PRIMARY KEY, deadline double precision, ready bigint);

CREATE TABLE reader_lists (
          identity TEXT PRIMARY KEY, scope TEXT, owner TEXT, sort TEXT, hidden bigint,
          version bigint NOT NULL, changed double precision NOT NULL, digest TEXT NOT NULL, pending bigint NOT NULL DEFAULT 0);

CREATE TABLE reader_material_links (
            kind TEXT, record TEXT, item TEXT, PRIMARY KEY(kind,record,item));

CREATE TABLE reader_originals (feed TEXT PRIMARY KEY, value bigint NOT NULL);

CREATE TABLE reader_problems (
              id TEXT PRIMARY KEY, identity TEXT NOT NULL, origin TEXT NOT NULL,
              body TEXT NOT NULL, created double precision NOT NULL, finished double precision, outcome TEXT);

CREATE TABLE reader_runtime (id bigint PRIMARY KEY CHECK(id=1), body TEXT NOT NULL);

CREATE TABLE reader_visibility (item TEXT PRIMARY KEY, hidden bigint NOT NULL DEFAULT 0);

CREATE TABLE reader_youtube_time (id bigint PRIMARY KEY CHECK(id=1), paused bigint NOT NULL);

CREATE TABLE settings (scope TEXT, owner TEXT, field TEXT, value TEXT,
          PRIMARY KEY(scope,owner,field));

CREATE TABLE source_deleted (item TEXT PRIMARY KEY);

CREATE TABLE state (key TEXT PRIMARY KEY,value TEXT);

CREATE TABLE telegram_avatars (feed TEXT PRIMARY KEY, image bytea NOT NULL, mime TEXT NOT NULL, digest TEXT NOT NULL);

CREATE TABLE telegram_bindings (feed TEXT PRIMARY KEY, binding TEXT NOT NULL);

CREATE TABLE telegram_claim_owners (
                kind TEXT, value TEXT, feed TEXT, evidence TEXT, PRIMARY KEY(kind,value,feed));

CREATE TABLE telegram_profiles (
                role TEXT PRIMARY KEY, account TEXT, user_id bigint, generation bigint NOT NULL,
                state TEXT, checked double precision, message TEXT);

CREATE TABLE telegram_read_dirty (feed TEXT PRIMARY KEY);

CREATE TABLE telegram_read_members (
          feed TEXT, member bigint, eligible bigint DEFAULT 0, reason TEXT, missing bigint DEFAULT 0,
          PRIMARY KEY(feed,member));

CREATE TABLE telegram_read_state (
          feed TEXT PRIMARY KEY, since double precision, initial bigint,
          confirmed bigint DEFAULT 0, signature TEXT, waiting TEXT, error TEXT);

CREATE TABLE telegram_source_claims (kind TEXT, value TEXT, PRIMARY KEY(kind,value));

CREATE TABLE thesis_inputs (item TEXT PRIMARY KEY,signature TEXT);

CREATE TABLE youtube_access (
              id bigint PRIMARY KEY CHECK(id=1), next_at double precision DEFAULT 0,
              blocked_until double precision DEFAULT 0, strikes bigint DEFAULT 0);

CREATE TABLE feed_publications (
          feed_id TEXT REFERENCES feeds(id), publication_id TEXT REFERENCES items(id),
          PRIMARY KEY(feed_id,publication_id));

CREATE TABLE media_files (
          id TEXT PRIMARY KEY, publication_id TEXT NOT NULL REFERENCES items(id), resource_key TEXT NOT NULL,
          source_locator TEXT NOT NULL, name TEXT NOT NULL, mime_type TEXT, size_bytes bigint,
          storage_key TEXT, status TEXT NOT NULL, reason TEXT NOT NULL DEFAULT '', resource_identity TEXT,
          UNIQUE(publication_id,resource_key));

CREATE TABLE publication_links (
          source_publication_id TEXT REFERENCES items(id), target_publication_id TEXT REFERENCES items(id),
          PRIMARY KEY(source_publication_id,target_publication_id));

