"""Repository database boundary; adapters own cursors and transaction mechanics."""
import sqlite3
import psycopg
from oko.storage.postgres_migrations import SchemaMismatch

from _thread import RLock
from collections.abc import Callable, Iterator, Sequence
from typing import Any, Literal, Protocol


class Row(Protocol):
    def __getitem__(self, key: int | str, /) -> Any: ...
    def __iter__(self) -> Iterator[Any]: ...
    def keys(self) -> Sequence[str]: ...


class Cursor(Protocol):
    @property
    def rowcount(self) -> int: ...
    def fetchone(self) -> Row | None: ...
    def fetchall(self) -> Sequence[Row]: ...
    def __iter__(self) -> Iterator[Row]: ...


class Database(Protocol):
    def execute(self, query: str, parameters: Any = (), /) -> Cursor: ...
    def executemany(self, query: str, parameters: Any, /) -> Any: ...
    def executescript(self, query: str, /) -> Any: ...
    @property
    def in_transaction(self) -> bool: ...
    def commit(self) -> None: ...
    def rollback(self) -> None: ...
    def close(self) -> None: ...
    def __enter__(self) -> 'Database': ...
    def __exit__(self, exc_type: Any, exc: Any, traceback: Any) -> Literal[False] | None: ...


class Connection(Database, Protocol):
    @property
    def access_lock(self) -> RLock: ...
    transaction_depth: int
    transaction_failed: bool
    before_commit: Callable[[], None] | None
    membership_feeds: set[str]
    membership_folders: set[str]
    def after_commit(self, callback: Callable[[], None]) -> None: ...
    def flush(self) -> None: ...


def expect_row(row: Row | None) -> Row:
    """A previously validated identity or aggregate must return one row."""
    if row is None:
        raise RuntimeError('Required storage row is missing')
    return row


DATABASE_ERRORS = (sqlite3.DatabaseError, psycopg.DatabaseError, SchemaMismatch)
INTEGRITY_ERRORS = (sqlite3.IntegrityError, psycopg.IntegrityError)
